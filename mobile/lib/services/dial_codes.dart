/// Indicatif d'un pays (par son code ISO), Maroc par défaut.
DialCode dialCodeFor(String? iso) => dialCodes.firstWhere((d) => d.iso == iso, orElse: () => dialCodes.first);

String _norm(String s) => s
    .toLowerCase()
    .replaceAll(RegExp('[éèêë]'), 'e')
    .replaceAll(RegExp('[àâäå]'), 'a')
    .replaceAll(RegExp('[ôö]'), 'o')
    .replaceAll(RegExp('[îï]'), 'i')
    .replaceAll(RegExp('[ûü]'), 'u')
    .replaceAll('ç', 'c');

/// Recherche par nom (français ou anglais, sans accents), code ISO ou indicatif (« 212 », « +33 »).
List<DialCode> searchDialCodes(String query) {
  final q = _norm(query.trim()).replaceFirst('+', '');
  if (q.isEmpty) return dialCodes;
  return dialCodes
      .where(
          (d) => _norm(d.fr).contains(q) || _norm(d.en).contains(q) || d.iso.toLowerCase() == q || d.dial.startsWith(q))
      .toList();
}
