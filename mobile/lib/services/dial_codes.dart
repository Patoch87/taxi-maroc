/// Indicatifs téléphoniques internationaux (liste UIT) : code ISO du pays, indicatif, nom en français et en anglais.
/// Maroc (+212) en premier, puis les autres pays par ordre alphabétique (en français).
class DialCode {
  const DialCode(this.iso, this.dial, this.fr, this.en);
  final String iso;
  final String dial;
  final String fr;
  final String en;

  /// Drapeau à partir du code ISO (deux lettres régionales).
  String get flag => String.fromCharCodes(iso.codeUnits.map((c) => 0x1F1E6 + c - 0x41));

  /// « +212 », ou « +1 264 » pour les pays du plan de numérotation nord-américain.
  String get code => dial.length == 4 && dial.startsWith('1') ? '+1 ${dial.substring(1)}' : '+$dial';

  /// Nom en français pour l'application en français, en anglais pour les autres langues.
  String name(String lang) => lang == 'fr' ? fr : en;
}

